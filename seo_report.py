"""The latest weekly SEO report (docs/informes/*.md, written by the SEO routine) as lib/seo-report.js, so the weekly summary
email (lib/weekly.js) can quote it: what was published, the Google reviews line, the visibility note and the drafts waiting
for someone. build.py runs it; the routine builds before it commits, so the file follows each report."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).parent
REPO = 'https://github.com/mmrtsv/casavella/blob/main/'


def plain(s):
    s = re.sub(r'\[([^\]]+)\]\([^)]+\)', r'\1', s)
    return re.sub(r'\s+', ' ', s.replace('**', '').replace('`', '')).strip()


def first_sentence(s):
    m = re.match(r'(.+?\.)(\s+[A-ZÀ-ÚÑ¿¡«(]|$)', s)
    return (m.group(1) if m else s).strip()


def sections(text):
    out, name = {}, ''
    for line in text.splitlines():
        if line.startswith('## '):
            name = line[3:].strip()
            out[name] = []
        elif name:
            out[name].append(line)
    return out


def latest():
    files = sorted((ROOT / 'docs' / 'informes').glob('????-??-??.md'))
    if not files:
        return None
    f = files[-1]
    text = f.read_text(encoding='utf-8')
    S = sections(text)
    published = []
    for line in S.get('Publicado', []):
        m = re.match(r'- \*\*(.+?)\*\*:?\s*(.*)', line)
        if m:
            published.append({'what': plain(m.group(1)), 'text': first_sentence(plain(m.group(2)))})
    reviews = next((plain(l[2:]) for l in S.get('Estado de la web', []) if 'Reseñas de Google' in l), '')
    visibility = next((first_sentence(plain(l)) for l in S.get('Visibilidad', []) if l.strip()), '')
    drafts = [plain(l[4:]) for l in S.get('Borradores para Màrius', []) if l.startswith('### ')]
    title = plain(text.splitlines()[0].lstrip('# '))
    return {'date': f.stem, 'title': title, 'published': published, 'reviews': reviews, 'visibility': visibility,
            'drafts': drafts, 'url': REPO + f.relative_to(ROOT).as_posix()}


def write():
    data = latest()
    (ROOT / 'lib' / 'seo-report.js').write_text(
        '// Generated by seo_report.py from the latest docs/informes/*.md (build.py). Don\'t edit by hand.\n'
        f'export const SEO = {json.dumps(data, ensure_ascii=False, indent=2)};\n', encoding='utf-8')


if __name__ == '__main__':
    write()
