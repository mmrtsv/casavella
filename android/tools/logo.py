# Traces the brand logo (img/logo-light.png) into vector paths for the app: res/raw/logo.json, drawn and animated by
# ui/Logo.kt, and the launcher icon's foreground (res/drawable/ic_launcher_foreground.xml). Only the PNG exists, so it is
# upscaled, smoothed and traced with potrace; the result is sharp at any size.
#   python3 -m venv /tmp/v && /tmp/v/bin/pip install potracer pillow numpy
#   /tmp/v/bin/python android/tools/logo.py        (from the repo root; ImageMagick's convert must be installed)
import json, os, subprocess, tempfile
import numpy as np, potrace
from PIL import Image

K = 8  # upscale factor; paths are written back in the PNG's own units (420 x 491)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, 'app/src/main/res')
src = os.path.join(os.path.dirname(ROOT), 'img/logo-light.png')

mask = os.path.join(tempfile.mkdtemp(), 'mask.png')
subprocess.run(['convert', src, '-alpha', 'extract', '-filter', 'Lanczos', '-resize', f'{K * 100}%', '-blur', '0x6',
                '-threshold', '50%', mask], check=True)
ink = np.array(Image.open(mask).convert('L')) < 127  # potrace's Bitmap fills the False pixels
curves = list(potrace.Bitmap(ink).trace(turdsize=40, alphamax=1.0, opticurve=True, opttolerance=0.2))

T = lambda p: (p.x, p.y)

def polygon(c):
    pts = [T(c.start_point)]
    for s in c.segments:
        if s.is_corner: pts += [T(s.c), T(s.end_point)]
        else:
            p0, c1, c2, e = pts[-1], T(s.c1), T(s.c2), T(s.end_point)
            for t in np.linspace(0.1, 1, 10):
                u = 1 - t
                pts.append(tuple(u**3 * p0[i] + 3 * u * u * t * c1[i] + 3 * u * t * t * c2[i] + t**3 * e[i] for i in (0, 1)))
    return np.array(pts)

def inside(pt, pg):
    x, y = pt; r = False; j = len(pg) - 1
    for i in range(len(pg)):
        (xi, yi), (xj, yj) = pg[i], pg[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi: r = not r
        j = i
    return r

P = [polygon(c) for c in curves]
area = [abs(np.dot(p[:, 0], np.roll(p[:, 1], 1)) - np.dot(p[:, 1], np.roll(p[:, 0], 1))) / 2 for p in P]
# Each contour's parent is the smallest one around it: even depth is ink, odd depth a hole in it
parent = []
for i, p in enumerate(P):
    around = [j for j in range(len(P)) if j != i and area[j] > area[i] and inside(tuple(p[0]), P[j])]
    parent.append(min(around, key=lambda j: area[j]) if around else None)
def depth(i): return 0 if parent[i] is None else 1 + depth(parent[i])

num = lambda v: f'{v / K:.2f}'.rstrip('0').rstrip('.')
pt = lambda p: f'{num(T(p)[0])} {num(T(p)[1])}'
def d(c):
    s = 'M' + pt(c.start_point)
    for g in c.segments:
        s += ('L' + pt(g.c) + 'L' + pt(g.end_point)) if g.is_corner else ('C' + pt(g.c1) + ' ' + pt(g.c2) + ' ' + pt(g.end_point))
    return s + 'Z'

parts = []
for i in range(len(P)):
    if depth(i) % 2: continue
    box = P[i] / K
    x0, y0, x1, y1 = (round(float(v), 1) for v in (box[:, 0].min(), box[:, 1].min(), box[:, 0].max(), box[:, 1].max()))
    # What each piece is, for the animation: the plant grows, then the name is written, then the details appear
    kind = 'plant' if y1 < 275 else 'name' if (y1 - y0) > 50 else 'detail'
    parts.append({'kind': kind, 'box': [x0, y0, x1, y1], 'd': d(curves[i]) + ''.join(d(curves[j]) for j in range(len(P)) if parent[j] == i)})
# Reading order: the name left to right, line by line
parts.sort(key=lambda p: (p['kind'] != 'plant', round(p['box'][1] / 60), p['box'][0]))

os.makedirs(os.path.join(RES, 'raw'), exist_ok=True)
with open(os.path.join(RES, 'raw/logo.json'), 'w') as f:
    json.dump({'w': ink.shape[1] / K, 'h': ink.shape[0] / K, 'parts': parts}, f, separators=(',', ':'))

# The icon: the plant in Cava on Verd fosc, inside the adaptive icon's 66 dp safe zone
plant = [p for p in parts if p['kind'] == 'plant']
x0 = min(p['box'][0] for p in plant); y0 = min(p['box'][1] for p in plant)
x1 = max(p['box'][2] for p in plant); y1 = max(p['box'][3] for p in plant)
s = 54 / (y1 - y0)
paths = '\n'.join(f'        <path android:fillColor="#F3EFE4" android:fillType="evenOdd" android:pathData="{p["d"]}" />' for p in plant)
with open(os.path.join(RES, 'drawable/ic_launcher_foreground.xml'), 'w') as f:
    f.write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by android/tools/logo.py from img/logo-light.png -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:scaleX="{s:.4f}" android:scaleY="{s:.4f}" android:translateX="{54 - (x0 + x1) / 2 * s:.3f}" android:translateY="{54 - (y0 + y1) / 2 * s:.3f}">
{paths}
    </group>
</vector>
''')
print(len(parts), 'parts:', {k: sum(p['kind'] == k for p in parts) for k in ('plant', 'name', 'detail')})
